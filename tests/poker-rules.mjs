import assert from 'node:assert/strict';
import {getGame,pokerAbsentAction} from '../dist/game-core/index.js';
import {PokerAbsenceRunner} from '../dist/poker-presence.js';
const engine=getGame('texas-holdem'),players=['ana','bea','carla'];
let state=engine.createInitialState(players,91);
const total=()=>Object.values(state.chips).reduce((a,b)=>a+b,0)+(['result','finished'].includes(state.phase)?0:Object.values(state.paid).reduce((a,b)=>a+b,0));
assert.equal(total(),3000);
assert.deepEqual(players.map(p=>state.chips[p]+state.paid[p]),[1000,1000,1000]);
for(let hand=1;hand<=6;hand++){
 assert.equal(state.smallBlindAmount,5+Math.floor((hand-1)/2)*5);
 assert.equal(state.bigBlindAmount,10+Math.floor((hand-1)/2)*5);
 assert.equal(engine.view(state,'ana').nextBlindHand,2*(Math.floor((hand-1)/2)+1)+1);
 while(state.phase!=='result')state=engine.applyAction(state,state.players[state.turn],{type:'fold'});
 assert.equal(total(),3000);assert.ok(Object.values(engine.view(state,'ana').street).every(n=>n===0));
 state=engine.applyAction(state,state.players[state.turn],{type:'next-hand'});
}
let now=0,away=new Set([state.players[state.turn]]),moves=0;
const runner=new PokerAbsenceRunner(()=>({engine,state,players:players.map(id=>({id,away:away.has(id)}))}),async move=>{state=engine.applyAction(state,move.playerId,move.action);moves++;},{delay:12000,clock:()=>now});
assert.equal(pokerAbsentAction(state).type,'fold');
await runner.tick();now=11999;await runner.tick();assert.equal(moves,0);
away.clear();now=13000;await runner.tick();assert.equal(moves,0,'reconnection cancels automatic fold');
away.add(state.players[state.turn]);await runner.tick();now=25000;await runner.tick();assert.equal(moves,1);
away=new Set(players);now=50000;await runner.tick();now=80000;await runner.tick();assert.equal(moves,1,'all absent waits');
state.phase='flop';state.currentBet=0;state.street[state.players[state.turn]]=0;assert.equal(pokerAbsentAction(state).type,'check');
state.chips[state.players[state.turn]]=0;assert.equal(pokerAbsentAction(state),null,'all-in remains eligible');
state.finished=true;assert.equal(pokerAbsentAction(state),null);
console.log('Póker: 1.000 fichas, niveles de ciegas, bote y ausencia/reenganche verificados.');
const {evaluatePokerHand,pokerPayout}=await import('../dist/game-core/index.js');
const card=(rank,suit='clubs')=>({id:`${suit}-${rank}`,rank,suit});
const royal=[card('A','hearts'),card('K','hearts'),card('Q','hearts'),card('J','hearts'),card('10','hearts')];
const exact=evaluatePokerHand([...royal,card('2'),card('3')]);
assert.equal(exact.score[0],8);assert.deepEqual(exact.cards,royal);
let round=engine.createInitialState(['a','b','c'],43),actor=round.players[round.turn];
assert.deepEqual(engine.view(round,'b').winningHands,{});
assert.throws(()=>engine.applyAction(round,actor,{type:'show-cards'}));
const moved=engine.applyAction(round,actor,{type:'raise',amount:40});
assert.equal(moved.lastAction.amount,40-round.street[actor]);assert.equal(moved.lastAction.target,40);
assert.equal(moved.lastAction.player,actor);assert.equal(moved.lastAction.sequence,1);
for(const id of round.players)assert.deepEqual(engine.view(moved,id).lastAction,moved.lastAction);
round=moved;while(round.phase!=='result')round=engine.applyAction(round,round.players[round.turn],{type:'fold'});
const winner=round.payouts[0].winners[0],loser=round.players.find(p=>p!==winner);
assert.deepEqual(engine.view(round,loser).publicHands[winner],[],'Fold win never reveals cards automatically');
assert.throws(()=>engine.applyAction(round,loser,{type:'show-cards'}));
assert.throws(()=>engine.applyAction(round,winner,{type:'show-cards',cards:[round.hands[loser][0].id]}));
round=engine.applyAction(round,winner,{type:'show-cards',cards:[round.hands[winner][0].id]});
assert.equal(engine.view(round,loser).publicHands[winner].length,1);assert.equal(engine.view(round,loser).publicHands[loser].length,0);
round=engine.applyAction(round,winner,{type:'show-cards',cards:[round.hands[winner][1].id]});
assert.equal(engine.view(round,loser).publicHands[winner].length,2);
const nextActor=round.players[round.turn];round=engine.applyAction(round,nextActor,{type:'next-hand'});
assert.equal(round.lastAction.player,nextActor);
assert.deepEqual(round.shownHands,{});assert.deepEqual(round.playerActions,{});assert.equal(round.lastAction.type,'deal');
let pots=engine.createInitialState(['a','b','c'],1);
Object.assign(pots,{board:royal,hands:{a:[card('2'),card('3')],b:[card('4'),card('5')],c:[card('6'),card('7')]},paid:{a:5,b:10,c:20},chips:{a:0,b:0,c:0},folded:{a:false,b:false,c:false},dealer:0});
pokerPayout(pots);
assert.deepEqual(pots.payouts.map(p=>p.pot),[15,10,10]);
assert.deepEqual(pots.payouts.map(p=>p.awards),[[{player:'b',amount:5},{player:'c',amount:5},{player:'a',amount:5}],[{player:'b',amount:5},{player:'c',amount:5}],[{player:'c',amount:10}]]);
assert.equal(pots.payouts[2].refund,true);assert.equal(Object.values(pots.chips).reduce((a,b)=>a+b),35);
// Odd chips follow clockwise order after dealer, with exact public award amounts.
Object.assign(pots,{paid:{a:5,b:5,c:5},chips:{a:0,b:0,c:0},folded:{a:false,b:false,c:true},finished:false});pokerPayout(pots);
assert.deepEqual(pots.payouts[0].awards,[{player:'b',amount:8},{player:'a',amount:7}]);
assert.equal(engine.view(pots,'a').publicHands.c.length,0);
assert.equal(engine.view(pots,'a').winningHands.c,undefined);
const {pokerTimeline,pokerBoardDelay}=await import('../dist/poker-events.js');
assert.equal(pokerBoardDelay(2,0),320);assert.equal(pokerBoardDelay(3,0),1520);assert.equal(pokerBoardDelay(4,0),2720);
assert.ok(pokerTimeline({...engine.view(pots,'a'),phase:'preflop',board:[]},engine.view(pots,'a')).total>=4500);
console.log('Póker: cartas ganadoras exactas, eventos públicos, revelación voluntaria, botes laterales, empates y secuencia de runout: OK');
